import {describe, expect, test} from 'vite-plus/test';

import {findDirective, stripDirective} from '../src/internal/directives.js';

describe('findDirective', () => {
  test('finds each kind on the first line, as ppx_weft writes it', () => {
    expect(
      findDirective("'use weft server'\n// Generated by ReScript\n"),
    ).toEqual({
      kind: 'server',
      start: 0,
      end: 17,
    });
    expect(findDirective("'use weft entrypoint'\nlet x = 1;\n")?.kind).toBe(
      'entrypoint',
    );
  });

  test('takes either quote, a semicolon, and other directives and comments first', () => {
    expect(findDirective('"use weft server";\n')).toEqual({
      kind: 'server',
      start: 0,
      end: 18,
    });
    const code =
      "// header\n/* block */\n'use strict';\n'use weft entrypoint'\n";
    const found = findDirective(code)!;
    expect(code.slice(found.start, found.end)).toBe("'use weft entrypoint'");
  });

  test("isn't fooled by the text elsewhere", () => {
    expect(findDirective("let x = 1;\n'use weft server'\n")).toBeUndefined();
    expect(findDirective("console.log('use weft server')\n")).toBeUndefined();
    expect(findDirective("'use weft server'.length\n")).toBeUndefined();
    expect(findDirective("'use weft client'\n")).toBeUndefined();
    expect(findDirective("'use weft server\n")).toBeUndefined();
    expect(findDirective('')).toBeUndefined();
  });

  test("ignores a statement's trailing comment", () => {
    expect(findDirective("'use weft server' // why\nlet x = 1\n")?.kind).toBe(
      'server',
    );
  });
});

describe('stripDirective', () => {
  test('blanks the directive out, keeping every other position', () => {
    const code = "'use weft server';\nexport let x = 1;\n";
    const stripped = stripDirective(code)!;
    expect(stripped).toBe(' '.repeat(18) + '\nexport let x = 1;\n');
    expect(stripped.length).toBe(code.length);
    expect(stripped.indexOf('export')).toBe(code.indexOf('export'));
  });

  test('leaves other directives alone, and gives nothing for a file without one', () => {
    expect(stripDirective("'use strict';\n'use weft entrypoint'\nx\n")).toBe(
      "'use strict';\n" + ' '.repeat(21) + '\nx\n',
    );
    expect(stripDirective('let x = 1;\n')).toBeUndefined();
  });
});
