import {readdirSync, readFileSync} from 'node:fs';
import {join, relative} from 'node:path';

import {describe, expect, test} from 'vite-plus/test';

import {findDirectives, stripDirectives} from '../src/internal/directives.js';
import {fixtures} from './support.js';

describe('findDirectives', () => {
  test('finds each kind on the first line, as ppx_weft writes it', () => {
    expect(
      findDirectives("'use weft server'\n// Generated by ReScript\n"),
    ).toEqual({
      kind: 'server',
      rpcs: [],
      css: false,
      directives: [{kind: 'server', start: 0, end: 17}],
    });
    expect(findDirectives("'use weft entrypoint'\nlet x = 1;\n")?.kind).toBe(
      'entrypoint',
    );
  });

  test("finds each RPC's, alone (a shared file) or beside an entrypoint one", () => {
    expect(
      findDirectives("'use weft rpc notes.save'\n'use weft rpc a.b_2'\nx\n"),
    ).toEqual({
      kind: 'shared',
      rpcs: ['notes.save', 'a.b_2'],
      css: false,
      directives: [
        {kind: 'rpc', rpc: 'notes.save', start: 0, end: 25},
        {kind: 'rpc', rpc: 'a.b_2', start: 26, end: 46},
      ],
    });
    const both = findDirectives("'use weft entrypoint'\n'use weft rpc a.b'\n")!;
    expect(both.kind).toBe('entrypoint');
    expect(both.rpcs).toEqual(['a.b']);
  });

  test("finds 'use weft css', alone (a shared file) or beside another", () => {
    expect(findDirectives("'use weft css'\nx\n")).toEqual({
      kind: 'shared',
      rpcs: [],
      css: true,
      directives: [{kind: 'css', start: 0, end: 14}],
    });
    const both = findDirectives("'use weft server'\n'use weft css'\n")!;
    expect([both.kind, both.css]).toEqual(['server', true]);
  });

  test("ignores an RPC directive whose ID isn't one", () => {
    expect(findDirectives("'use weft rpc __proto__'\n")).toBeUndefined();
    expect(findDirectives("'use weft rpc a..b'\n")).toBeUndefined();
    expect(findDirectives("'use weft rpc '\n")).toBeUndefined();
  });

  test('takes either quote, a semicolon, and other directives and comments first', () => {
    expect(findDirectives('"use weft server";\n')?.directives).toEqual([
      {kind: 'server', start: 0, end: 18},
    ]);
    const code =
      "// header\n/* block */\n'use strict';\n'use weft entrypoint'\n";
    const [found] = findDirectives(code)!.directives;
    expect(code.slice(found!.start, found!.end)).toBe("'use weft entrypoint'");
  });

  test("isn't fooled by the text elsewhere", () => {
    expect(findDirectives("let x = 1;\n'use weft server'\n")).toBeUndefined();
    expect(findDirectives("console.log('use weft server')\n")).toBeUndefined();
    expect(findDirectives("'use weft server'.length\n")).toBeUndefined();
    expect(findDirectives("'use weft client'\n")).toBeUndefined();
    expect(findDirectives("'use weft server\n")).toBeUndefined();
    expect(findDirectives('')).toBeUndefined();
  });

  test("ignores a statement's trailing comment", () => {
    expect(findDirectives("'use weft server' // why\nlet x = 1\n")?.kind).toBe(
      'server',
    );
  });
});

describe('stripDirectives', () => {
  test('blanks the directives out, keeping every other position', () => {
    const code = "'use weft server';\nexport let x = 1;\n";
    const stripped = stripDirectives(code)!;
    expect(stripped).toBe(' '.repeat(18) + '\nexport let x = 1;\n');
    expect(stripped.length).toBe(code.length);
    expect(stripped.indexOf('export')).toBe(code.indexOf('export'));
  });

  test('leaves other directives alone, and gives nothing for a file without one', () => {
    expect(stripDirectives("'use strict';\n'use weft entrypoint'\nx\n")).toBe(
      "'use strict';\n" + ' '.repeat(21) + '\nx\n',
    );
    expect(
      stripDirectives("'use weft entrypoint'\n'use weft rpc a.b'\nx\n"),
    ).toBe(' '.repeat(21) + '\n' + ' '.repeat(18) + '\nx\n');
    expect(stripDirectives('let x = 1;\n')).toBeUndefined();
  });
});

/** The compiled files under `dir`, as paths from `root`, leaving out dependencies and build caches. */
function compiledFiles(dir: string, root = dir): string[] {
  return readdirSync(dir, {withFileTypes: true}).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return ['node_modules', 'lib'].includes(entry.name)
        ? []
        : compiledFiles(path, root);
    }
    return entry.name.endsWith('.res.js') ? [relative(root, path)] : [];
  });
}

describe('on what ppx_weft wrote', () => {
  // Every compiled file in the fixtures, and the directives its source calls for.
  const compiled = compiledFiles(fixtures).sort();
  const expected: Record<string, string> = {
    'basic/src/Api.res.js': 'shared',
    'basic/src/Later.res.js': 'entrypoint',
    'basic/src/Likes.res.js': 'entrypoint',
    'basic/src/Notes.res.js': 'server',
    'basic/src/Panels.res.js': 'entrypoint',
    'basic/src/Popover.res.js': 'shared',
    'basic/src/Theme.res.js': 'shared',
    'basic/src/nested/Deep.res.js': 'entrypoint',
    'basic/tests/Fake.res.js': 'entrypoint',
    'client_imports_server/src/Db.res.js': 'server',
    'styled/src/Card.res.js': 'shared',
    'styled/src/Later.res.js': 'shared',
    'styled/src/Theme.res.js': 'shared',
    'widgets/src/Widget.res.js': 'entrypoint',
  };

  const styled = new Set([
    'basic/src/Notes.res.js',
    'basic/src/Popover.res.js',
    'basic/src/Theme.res.js',
    'styled/src/Card.res.js',
    'styled/src/Later.res.js',
    'styled/src/Theme.res.js',
    'widgets/src/Widget.res.js',
  ]);

  const rpcs: Record<string, string[]> = {
    'basic/src/Api.res.js': ['basic.save', 'basic.remove'],
    'widgets/src/Widget.res.js': ['widgets.press'],
  };

  test.each(compiled)('%s', (file) => {
    const code = readFileSync(join(fixtures, file), 'utf8');
    const found = findDirectives(code);
    expect(found?.kind).toBe(expected[file]);
    expect(found?.rpcs ?? []).toEqual(rpcs[file] ?? []);
    expect(found?.css ?? false).toBe(styled.has(file));
    if (found !== undefined) {
      // Stripped, it's ordinary ReScript output, with nothing else moved.
      const stripped = stripDirectives(code, found)!;
      expect(stripped.length).toBe(code.length);
      expect(findDirectives(stripped)).toBeUndefined();
      expect(stripped.trimStart()).toMatch(/^\/\/ Generated by ReScript/);
    }
  });
});
